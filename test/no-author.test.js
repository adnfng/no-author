const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const http = require('node:http')
const os = require('node:os')
const path = require('node:path')
const { execFileSync, spawn } = require('node:child_process')
const {
  cleanMessage,
  confirmAnonymousEvent,
  prepareAnonymousEvent,
  readQueuedEventCount,
  reportAnonymousEvent,
  telemetryEnabled,
} = require('../bin/no-author.js')

const emptyConfig = { emails: new Set(), lines: new Set() }

function run(command, args, options) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, options)
    let stdout = ''
    let stderr = ''

    child.stdout.on('data', (chunk) => (stdout += chunk))
    child.stderr.on('data', (chunk) => (stderr += chunk))
    child.on('error', reject)
    child.on('close', (code) => {
      if (code === 0) resolve({ stdout, stderr })
      else reject(new Error(`${command} exited with ${code}: ${stderr}`))
    })
  })
}

test('removes known AI co-author trailers', () => {
  const message = `Fix the thing

Co-authored-by: Cursor <cursoragent@cursor.com>
Co-Authored-By: Claude <noreply@anthropic.com>
Co-authored-by: Codex <noreply@openai.com>
Co-authored-by: Gemini <gemini-code-assist@google.com>
Co-authored-by: aider (sonnet) <aider@aider.chat>
Co-authored-by: Copilot <198982749+Copilot[bot]@users.noreply.github.com>
`

  const result = cleanMessage(message, emptyConfig)

  assert.equal(result.message, 'Fix the thing\n')
  assert.equal(result.removed, 6)
})

