test('allows repository-level telemetry opt-out', () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'no-author-'))
  fs.writeFileSync(
    path.join(directory, '.no-author.json'),
    '{"telemetry":false}\n',
  )

  try {
    assert.equal(telemetryEnabled(directory), false)
  } finally {
    fs.rmSync(directory, { recursive: true, force: true })
  }
})

test('keeps an anonymous event queued until the counter accepts it', async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'no-author-'))
  const previousEndpoint = process.env.NO_AUTHOR_ENDPOINT
  const previousTelemetry = process.env.NO_AUTHOR_TELEMETRY
  let server

  execFileSync('git', ['init', '--quiet', directory])
  delete process.env.NO_AUTHOR_TELEMETRY

  try {
    prepareAnonymousEvent(directory)
    confirmAnonymousEvent(directory)
    assert.equal(readQueuedEventCount(directory), 1)

    process.env.NO_AUTHOR_ENDPOINT = 'http://127.0.0.1:1'
    await reportAnonymousEvent(directory)
    assert.equal(readQueuedEventCount(directory), 1)

    server = http.createServer((request, response) => {
      assert.equal(request.method, 'POST')
      response.writeHead(201).end()
    })
    await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve))

    process.env.NO_AUTHOR_ENDPOINT = `http://127.0.0.1:${server.address().port}`
    await reportAnonymousEvent(directory)
    assert.equal(readQueuedEventCount(directory), 0)
  } finally {
    await new Promise((resolve) => server?.close(resolve) ?? resolve())
    fs.rmSync(directory, { recursive: true, force: true })

    if (previousEndpoint === undefined) delete process.env.NO_AUTHOR_ENDPOINT
    else process.env.NO_AUTHOR_ENDPOINT = previousEndpoint

    if (previousTelemetry === undefined) delete process.env.NO_AUTHOR_TELEMETRY
    else process.env.NO_AUTHOR_TELEMETRY = previousTelemetry
  }
})

test('installed Git hooks clean and report a real commit', async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'no-author-hook-'))
  const executable = path.resolve(__dirname, '../bin/no-author.js')
  let requests = 0
  const server = http.createServer((request, response) => {
    requests += 1
    assert.equal(request.method, 'POST')
    assert.equal(request.headers['content-length'], '0')

    if (requests === 1) {
      request.socket.destroy()
      return
    }

    assert.match(request.headers['user-agent'], /^curl\//)
    response.writeHead(201).end()
  })

  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve))

  try {
    const gitEnvironment = {
      ...process.env,
      GIT_CONFIG_GLOBAL: '/dev/null',
      GIT_CONFIG_NOSYSTEM: '1',
      NO_AUTHOR_ENDPOINT: `http://127.0.0.1:${server.address().port}`,
    }

    execFileSync('git', ['init', '--quiet'], { cwd: directory, env: gitEnvironment })
    execFileSync('git', ['config', 'user.name', 'Noa Test'], {
      cwd: directory,
      env: gitEnvironment,
    })
    execFileSync('git', ['config', 'user.email', 'noa@example.com'], {
      cwd: directory,
      env: gitEnvironment,
    })
    execFileSync(process.execPath, [executable, 'install'], {
      cwd: directory,
      env: gitEnvironment,
      stdio: 'ignore',
    })
    fs.writeFileSync(path.join(directory, 'README.md'), '# Test\n')
    execFileSync('git', ['add', 'README.md'], {
      cwd: directory,
      env: gitEnvironment,
    })

    await run(
      'git',
      [
        'commit',
        '--quiet',
        '-m',
        'Test commit',
        '--trailer',
        'Co-authored-by: Cursor <cursoragent@cursor.com>',
      ],
      { cwd: directory, env: gitEnvironment },
    )

    const message = execFileSync('git', ['log', '-1', '--format=%B'], {
      cwd: directory,
      env: gitEnvironment,
      encoding: 'utf8',
    })
    assert.equal(message, 'Test commit\n\n')
    assert.equal(requests, 2)
    assert.equal(readQueuedEventCount(directory), 0)
  } finally {
    await new Promise((resolve) => server.close(resolve))
    fs.rmSync(directory, { recursive: true, force: true })
  }
})
